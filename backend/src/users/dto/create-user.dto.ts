import {
  IsEmail,
  IsEnum,
  IsOptional,
  IsString,
  MinLength,
} from 'class-validator';
import { Role } from '@prisma/client';

export class CreateUserDto {
  @IsString()
  @MinLength(2)
  name!: string;

  @IsEmail()
  email!: string;

  @IsString()
  @MinLength(8)
  password!: string;

  @IsEnum(Role)
  role!: Role;

  /** Obrigatória na prática para CONSULTOR/GERENTE; CREDITO/ADMIN não têm filial. */
  @IsOptional()
  @IsString()
  branchId?: string;
}
